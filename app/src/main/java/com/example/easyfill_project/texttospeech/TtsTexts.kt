    /**
     * Returns the full-screen explanation for the current step
     * of the housing assistance form.
     * The step numbers must match the section numbers inside
     * HousingAssistanceFormScreen.
     */
    fun getHousingAssistanceStepText(step: Int): String {
        return when (step) {

            // PersonalDetailsSection
            0 -> """
            הגעתם לשלב הראשון בטופס סיוע בדיור: פרטים אישיים.
            בשלב זה יש למלא את הפרטים האישיים שלכם,
            כמו שם, מספר זהות ופרטי קשר.
        """.trimIndent()

            // MailingAddressSection
            1 -> """
            הגעתם לשלב השני בטופס סיוע בדיור: כתובת למשלוח דואר.
            בשלב זה יש למלא את פרטי הכתובת שלכם,
            כמו עיר, רחוב, מספר בית ומיקוד.
        """.trimIndent()

            // FamilyStatusSection
            2 -> """
            הגעתם לשלב השלישי בטופס סיוע בדיור: מצב משפחתי.
            בשלב זה יש למלא מידע על המצב המשפחתי
            ועל בני המשפחה המתגוררים אתכם.
        """.trimIndent()

            // IncomeDetailsSection
            3 -> """
            הגעתם לשלב הרביעי בטופס סיוע בדיור: פרטי הכנסה.
            בשלב זה יש למלא מידע על ההכנסות שלכם
            ועל מקורות הכנסה נוספים, אם קיימים.
        """.trimIndent()

            // AssistanceSelectionSection
            4 -> """
            הגעתם לשלב החמישי בטופס סיוע בדיור: בחירת סוג הסיוע.
            בשלב זה יש לבחור את סוג הסיוע המתאים
            לפי הצורך והמצב שלכם.
        """.trimIndent()

            // RentAssistanceSection
            5 -> """
            הגעתם לשלב השישי בטופס סיוע בדיור: פרטי סיוע בשכר דירה.
            בשלב זה יש למלא פרטים על הדירה,
            חוזה השכירות ותשלומי שכר הדירה.
        """.trimIndent()

            // SummarySection
            6 -> """
            הגעתם לשלב האחרון בטופס סיוע בדיור: סיכום.
            במסך זה אפשר לעבור על כל הפרטים שמילאתם,
            לבדוק שהם נכונים ולחזור לשלבים קודמים במקרה הצורך.
            לאחר הבדיקה ניתן להמשיך ולסיים את התהליך.
        """.trimIndent()

            // Fallback in case an invalid step is received.
            else -> """
            אתם נמצאים בטופס סיוע בדיור.
            יש למלא את השדות לפי ההוראות המוצגות במסך.
        """.trimIndent()
        }
    }
